export function fillMessage(template, booking, left = 0) {
  if (!template) return ''
  const n = nightsOf(booking)
  const values = {
    '{имя}': booking.guest_name || '',
    '{заезд}': fmtDate(booking.check_in),
    '{выезд}': booking.check_out ? fmtDate(booking.check_out) : 'по договорённости',
    '{ночей}': n ? nightsLabel(n) : 'помесячно',
    '{сумма}': money(booking.mode === 'daily' ? booking.price_total : booking.monthly_rate),
    '{осталось}': money(left),
    '{код}': booking.access_code || '',
  }
  let text = template
  for (const [k, v] of Object.entries(values)) text = text.split(k).join(v)
  // если имени нет — убираем «, » перед пустым местом: «Добро пожаловать, !» → «Добро пожаловать!»
  return text.replace(/,\s*([!.])/g, '$1').trim()
}

